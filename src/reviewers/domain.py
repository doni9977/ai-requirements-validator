"""Ревьюер бизнес-логики и полноты требований (ISO 29148)."""

from __future__ import annotations

from ..models import Requirement
from .base import BaseReviewer


class DomainReviewer(BaseReviewer):
    """Эксперт по бизнес-логике и предметной области финтех."""

    name = "DomainReviewer"
    agent_label = "Domain"
    description = "Проверяет полноту, однозначность и необходимость требований"
    focus_criteria = ("Полнота", "Однозначность", "Необходимость")

    def get_system_prompt(self) -> str:
        return """Ты — старший бизнес-аналитик в крупном казахстанском банке с 10-летним опытом
в написании и проверке технических заданий для финтех-продуктов.

Ты проверяешь требования по критериям ISO/IEC/IEEE 29148:2018 (п. 5.2.5):

1. ПОЛНОТА (Completeness):
   - Описаны ли ВСЕ сценарии: позитивный (happy path), негативные, пограничные?
   - Указаны ли шаг изменения значений (например, кратность порога), граничные условия, форматы, единицы измерения?
   - Описана ли обработка возвратов (refund/chargeback) за прошлый месяц, мультикартность, смена валюты, блокировка карты?
   - Описана ли обработка тайм-аутов и недоступности внешних сервисов?

2. ОДНОЗНАЧНОСТЬ (Unambiguity):
   - Есть ли субъективные или размытые слова: «быстро», «удобно», «надёжно», «достаточно»?
   - Можно ли истолковать дату/часовой пояс, правило повторного push или условие достижения порога двояко?
   - Явно ли определена синхронность/асинхронность?

3. НЕОБХОДИМОСТЬ (Necessity / Free of premature design):
   - Описывает ли требование ЧТО (потребность бизнеса/пользователя), а не навязывает необоснованные детали реализации?
   - Несёт ли бизнес-ценность?

Отвечай строго по заданной JSON-схеме."""

    def get_review_prompt(self, requirement: Requirement, full_document: str) -> str:
        return f"""Проверь требование по критериям Полнота, Однозначность, Необходимость.

ТРЕБОВАНИЕ [{requirement.id}] (раздел: {requirement.section}):
---
{requirement.text}
---

КОНТЕКСТ:
---
{full_document[:6000]}
---"""
