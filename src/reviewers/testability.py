"""Ревьюер тестируемости и критериев приёмки."""

from __future__ import annotations

from ..models import Requirement
from .base import BaseReviewer


class TestabilityReviewer(BaseReviewer):
    """Эксперт по QA, тестируемости и критериям приёмки."""

    name = "TestabilityReviewer"
    agent_label = "QA"
    description = "Проверяет возможность тестирования и согласованность критериев приёмки"
    focus_criteria = ("Тестируемость",)

    def get_system_prompt(self) -> str:
        return """Ты — Lead QA Engineer в финтех-компании с опытом тестирования
мобильного банкинга и карточного процессинга.

Ты проверяешь требования по критерию ПРОВЕРЯЕМОСТЬ / ТЕСТИРУЕМОСТЬ (ISO/IEC/IEEE 29148 п. 5.2.5):

1. ТЕСТИРУЕМОСТЬ:
   - Можно ли на основе формулировки написать детерминированный тест-кейс с однозначным Expected Result?
   - Определены ли конкретные числовые SLA, граничные значения (например, 999, 1000, 1000000, 1000001) и негативные сценарии?
   - Отсутствуют ли заглушки вроде «заполняются тестировщиками», «TBD»?

2. КАЧЕСТВО И НЕПРОТИВОРЕЧИВОСТЬ КРИТЕРИЕВ ПРИЁМКИ:
   - Нет ли конфликта между критериями приёмки и функциональными требованиями (например, покупка 31 января в 23:58 и проводка 1 февраля в 00:03: учёт по дате совершения покупки vs по дате проводки)?
   - Покрыты ли в приёмке возвраты, повторные события процессинга, ошибки 400/401/403/404/500, изменение порога?

Отвечай строго по заданной JSON-схеме."""

    def get_review_prompt(self, requirement: Requirement, full_document: str) -> str:
        return f"""Проверь тестируемость требования и его связь с критериями приёмки.

ТРЕБОВАНИЕ [{requirement.id}] (раздел: {requirement.section}):
---
{requirement.text}
---

КОНТЕКСТ:
---
{full_document[:6000]}
---"""
